#!/usr/bin/env node
/**
 * Internal link matrix. Run after astro build (part of `npm run check:links`).
 *
 *   node scripts/check-internal-links.mjs [distDir]      (default: dist)
 *
 * Counts CONTEXTUAL links only: links inside <main>, from one page to another.
 * The site header, footer and mobile CTA bar sit outside <main> and do not count.
 *
 * Fails (exit 1) when:
 *  - a money page has contextual links from fewer than MIN_SOURCES other pages
 *  - any indexable page (in sitemap.xml) other than the home page has no
 *    contextual link at all (an orphan in the body of the site)
 *  - a contextual link uses generic anchor text ("click here", "read more", ...)
 *
 * Writes the matrix to docs/seo/internal-link-matrix.md.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, resolve, relative } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const dist = resolve(process.argv[2] ?? join(ROOT, "dist"));
const REPORT = join(ROOT, "docs", "seo", "internal-link-matrix.md");
const MIN_SOURCES = 3;
/** Pages that earn bookings, quotes or leads. */
const MONEY_PAGES = [
  "/menu/",
  "/menu/dosa/",
  "/menu/nellai-meals/",
  "/veg-dinner-anna-nagar/",
  "/corporate-catering-chennai/",
  "/catering-services-chennai/",
  "/event-planner-catering-partner/",
  "/book-a-table/",
  "/about/",
];
const GENERIC = /^(?:click here|here|read more|learn more|more|link|this page|this|go|see more)$/i;

if (!existsSync(dist)) {
  console.error(`✖ ${dist} not found. Run astro build first.`);
  process.exit(2);
}

function* walk(p) {
  if (statSync(p).isFile()) return yield p;
  for (const e of readdirSync(p)) yield* walk(join(p, e));
}
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&nbsp;/g, " ");
const text = (s) => decode(s.replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();

const sitemap = existsSync(join(dist, "sitemap.xml")) ? readFileSync(join(dist, "sitemap.xml"), "utf8") : "";
const origin = sitemap.match(/<loc>(https?:\/\/[^/]+)/)?.[1] ?? "";
const indexable = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].slice(origin.length) || "/");

const pages = new Map(); // path -> html
for (const f of walk(dist)) {
  if (!f.endsWith("index.html")) continue;
  const rel = "/" + relative(dist, f).replace(/\\/g, "/").replace(/index\.html$/, "");
  pages.set(rel, readFileSync(f, "utf8"));
}

const inbound = new Map(); // target -> Map(source -> [anchors])
const errors = [];
for (const [path, html] of pages) {
  const main = html.match(/<main\b[\s\S]*?<\/main>/i)?.[0] ?? "";
  for (const m of main.matchAll(/<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi)) {
    let href = decode(m[1]);
    if (/^(?:https?:)?\/\//.test(href) && !href.startsWith(origin)) continue; // external
    if (/^(?:tel|mailto|https?:\/\/wa\.me)/.test(href) || href.startsWith("#")) continue;
    if (origin && href.startsWith(origin)) href = href.slice(origin.length);
    const target = new URL(href, `https://x${path}`).pathname.replace(/([^/])$/, "$1/");
    if (target === path || !pages.has(target)) continue;
    const anchor = text(m[2]);
    if (GENERIC.test(anchor)) errors.push(`${path}: generic anchor "${anchor}" -> ${target}`);
    if (!inbound.has(target)) inbound.set(target, new Map());
    const bySource = inbound.get(target);
    if (!bySource.has(path)) bySource.set(path, []);
    bySource.get(path).push(anchor);
  }
}

const sourcesOf = (t) => inbound.get(t) ?? new Map();
for (const t of MONEY_PAGES) {
  if (!pages.has(t)) continue;
  const n = sourcesOf(t).size;
  if (n < MIN_SOURCES) errors.push(`money page ${t}: contextual links from ${n} page(s) (needs ${MIN_SOURCES})`);
}
for (const t of indexable) {
  if (t === "/") continue;
  if (!sourcesOf(t).size) errors.push(`orphan: ${t} has no contextual link from any other page`);
}

const lines = ["# Internal link matrix", ""];
lines.push(`Generated by \`scripts/check-internal-links.mjs\` on ${new Date().toISOString().slice(0, 10)}. Contextual links only: links inside \`<main>\` from another page (header, footer and the mobile CTA bar are not counted). Money pages need links from at least ${MIN_SOURCES} pages; every indexable page needs at least one.`, "");
lines.push(`**Result: ${errors.length ? `FAILED, ${errors.length} problem(s)` : "PASSED"}**`, "");
lines.push("| Page | Money page | Linking pages | Linked from (anchor text) |", "|---|---|---|---|");
for (const t of [...indexable].sort()) {
  const src = sourcesOf(t);
  const detail = [...src.entries()].map(([s, a]) => `\`${s}\` (${[...new Set(a)].map((x) => `"${x}"`).join(", ")})`).join("; ");
  lines.push(`| \`${t}\` | ${MONEY_PAGES.includes(t) ? "yes" : ""} | ${src.size} | ${detail || "none"} |`);
}
if (errors.length) lines.push("", "## Problems", "", ...errors.map((e) => `- ${e}`));
writeFileSync(REPORT, lines.join("\n") + "\n");

if (errors.length) {
  console.error(`✖ internal link matrix failed (${errors.length} problem(s)). Report: ${relative(ROOT, REPORT)}`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
console.log(`✔ internal link matrix passed (${indexable.length} indexable page(s), ${MONEY_PAGES.length} money page(s) with ${MIN_SOURCES}+ linking pages). Report: ${relative(ROOT, REPORT)}`);
